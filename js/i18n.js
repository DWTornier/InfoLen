const DICTS = { en, zh };

let current = "en";
try {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved && DICTS[saved]) current = saved;
} catch { /* localStorage 不可用时保持默认 */ }

export function getLocale() {
  return current;
}

export function setLocale(locale) {
  if (!DICTS[locale]) return;
  current = locale;
  try { localStorage.setItem(STORAGE_KEY, locale); } catch { /* ignore */ }
  document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
}

/** 翻译：支持 {param} 占位 */
export function t(key, params) {
  const dict = DICTS[current] || en;
  let str = dict[key];
  if (str === undefined) str = en[key];
  if (str === undefined) return key;
  if (params) {
    str = str.replace(/\{(\w+)\}/g, (m, name) => (params[name] !== undefined ? String(params[name]) : m));
  }
  return str;
}

/** 应用静态 DOM 上标注的 data-i18n / data-i18n-title / data-i18n-aria */
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    const val = t(node.dataset.i18n);
    if (val) node.innerHTML = val;
  });
  root.querySelectorAll("[data-i18n-title]").forEach((node) => {
    const val = t(node.dataset.i18nTitle);
    if (val) {
      node.title = val;
      node.setAttribute("aria-label", val);
    }
  });
}
